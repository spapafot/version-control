/**
 * Regenerates docs/seo/keyword-map.md from the metadata in src/.
 *
 * The map is a document people read, but every fact in it already lives in
 * src/challenges/seo.ts and src/lib/page-seo.ts. Maintaining a second copy of
 * 69 titles by hand guarantees the two drift, so this derives it instead.
 *
 * It reads those two files as text rather than importing them: the challenge
 * modules use extensionless relative imports and a "@/" alias, neither of which
 * plain Node resolves, and a doc generator is not worth a build step.
 *
 * Run: pnpm seo:keywords
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

/**
 * Authoritative world order, read from the SECTIONS array.
 *
 * seo.ts groups missions under `// ── Section title ──` banners, which say
 * nothing about ordering on purpose: the worlds have been renumbered before,
 * and a hardcoded number in a comment silently goes stale. The banner supplies
 * only the grouping; the world number and blurb come from here.
 */
function parseSections(source) {
  const sections = new Map();
  for (const m of source.matchAll(
    /world:\s*(\d+),\s*\n\s*title:\s*"((?:[^"\\]|\\.)*)",\s*\n\s*blurb:\s*\n?\s*"((?:[^"\\]|\\.)*)"/g,
  )) {
    sections.set(m[2], { world: Number(m[1]), title: m[2], blurb: m[3] });
  }
  return sections;
}

/** Pulls `key: "value"` and `key: [...]` out of one object literal block. */
function parseEntries(source, { sectionBanners = false } = {}) {
  const entries = [];
  let group = null;

  // one pass over the file, tracking section banners and top-level keys
  const re = sectionBanners
    ? /\/\/\s*──+\s*([^─\n]+?)\s*──+|^ {2}"([^"]+)": \{([\s\S]*?)\n {2}\},/gm
    : /^ {2}"([^"]+)": \{([\s\S]*?)\n {2}\},/gm;

  for (const m of source.matchAll(re)) {
    if (sectionBanners && m[1] && !m[2]) {
      group = m[1].trim();
      continue;
    }
    const key = sectionBanners ? m[2] : m[1];
    const body = sectionBanners ? m[3] : m[2];
    if (!key) continue;

    const str = (name) => {
      // values may be split across lines by the formatter
      const hit = body.match(new RegExp(`${name}:\\s*((?:"(?:[^"\\\\]|\\\\.)*"\\s*\\+?\\s*)+),`));
      if (!hit) return "";
      return [...hit[1].matchAll(/"((?:[^"\\]|\\.)*)"/g)]
        .map((s) => s[1].replace(/\\"/g, '"').replace(/\\\\/g, "\\"))
        .join("");
    };
    const arr = (name) => {
      const hit = body.match(new RegExp(`${name}:\\s*\\[([\\s\\S]*?)\\]`));
      return hit ? [...hit[1].matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((s) => s[1]) : [];
    };

    entries.push({
      key,
      group,
      keyword: str("keyword"),
      title: str("title"),
      description: str("description"),
      teaches: arr("teaches"),
      secondary: arr("secondary"),
    });
  }
  return entries;
}

const missions = parseEntries(readFileSync("src/challenges/seo.ts", "utf8"), {
  sectionBanners: true,
});
const pages = parseEntries(readFileSync("src/lib/page-seo.ts", "utf8"));
const sections = parseSections(readFileSync("src/challenges/types.ts", "utf8"));

if (missions.length === 0 || pages.length === 0 || sections.size === 0) {
  console.error("parsed nothing; the source formatting probably changed");
  process.exit(1);
}

// every mission must sit under a banner that names a real section
const orphans = [...new Set(missions.map((m) => m.group))].filter((g) => !sections.has(g));
if (orphans.length) {
  console.error(`seo.ts banners do not match any section title: ${orphans.join(", ")}`);
  process.exit(1);
}

// group in the order SECTIONS declares, not the order seo.ts happens to use
const grouped = [...sections.values()]
  .sort((a, b) => a.world - b.world)
  .map((section) => ({
    section,
    missions: missions.filter((m) => m.group === section.title),
  }))
  .filter((g) => g.missions.length > 0);

const esc = (s) => s.replace(/\|/g, "\\|");
const out = [];
const w = (...lines) => out.push(...lines);

w(
  "<!-- Generated by scripts/gen-keyword-map.mjs. Edit src/challenges/seo.ts",
  "     or src/lib/page-seo.ts and re-run `pnpm seo:keywords`. -->",
  "",
  "# Keyword map",
  "",
  `Every indexable URL on versioncontrol.gr (${pages.length} top-level pages plus ${missions.length} missions),`,
  "the query each one is written for, and the metadata it ships.",
  "",
  "## Targeting",
  "",
  "English, global. The `.gr` domain is not treated as a Greek-language signal: the course",
  "is written in English, and Greek developers search these topics in English. There are no",
  "`/el/` routes and no hreflang beyond `en`.",
  "",
  "Head terms are saturated. Searches like \"learn git\" and \"git tutorial\" are held by",
  "learngitbranching.js.org, boot.dev, Codecademy, gitbybit and git-practice.com, all with",
  "far more authority than a new site. The strategy is therefore the long tail: one mission",
  "page per specific problem a developer actually types into Google mid-panic, such as",
  "\"git reset vs revert\", \"fix detached HEAD\" or \"push rejected non-fast-forward\".",
  "",
  "## Top-level pages",
  "",
  "These keep the site-name suffix from the layout title template, so their titles are",
  "written short enough to leave room for it.",
  "",
  "| URL | Primary keyword | Secondary | Title | Description |",
  "| --- | --- | --- | --- | --- |",
);

for (const p of pages) {
  w(
    `| \`${p.key}\` | ${esc(p.keyword)} | ${esc(p.secondary.join("; "))} | ${esc(p.title)} | ${esc(p.description)} |`,
  );
}

w(
  "",
  "## Mission pages",
  "",
  `${missions.length} long-tail pages, one per mission, and the main reason this site can rank at all.`,
  "",
  "Two things are deliberate here. Mission titles are **absolute**, with no site-name",
  "suffix, so the whole SERP budget goes to the keyword. And the keyword title runs",
  "*alongside* the on-screen title rather than replacing it: the course keeps its own voice",
  "(\"The Referee\", \"! [rejected]\", \"The urgent phone call\") while search engines get the",
  "Git command. See `src/challenges/seo.ts`.",
  "",
);

for (const { section, missions: group } of grouped) {
  w(
    "",
    `### World ${section.world}: ${section.title}`,
    "",
    section.blurb,
    "",
    "| URL | Primary keyword | Title | Teaches |",
    "| --- | --- | --- | --- |",
  );
  for (const m of group) {
    w(
      `| \`/challenge/${m.key}/\` | ${esc(m.keyword)} | ${esc(m.title)} | ${esc(m.teaches.join("; "))} |`,
    );
  }
}

w(
  "",
  "## Deliberate omissions",
  "",
  "Each of these is a thing a checklist would tell you to add, left out on purpose:",
  "",
  "- **`meta keywords`.** Google ignores it, and a stuffed list is a spam signal rather than a ranking factor.",
  "- **`FAQPage` schema.** The site has no FAQ content. Marking up questions a visitor cannot see is what earns a manual action.",
  "- **`SearchAction` in `WebSite`.** There is no site search to point it at.",
  "- **`courseWorkload` in `CourseInstance`.** No completion time has been measured, and inventing one would put a false figure into structured data.",
  "- **Per-mission OG images.** Social cards do not affect ranking, and 74 build-time images buy little over one good site-wide card.",
  "",
  "## Known gap: apex vs www",
  "",
  "`versioncontrol.gr` and `www.versioncontrol.gr` are both live custom domains in",
  "`wrangler.jsonc`, which is duplicate content. Every canonical points at the apex, and",
  "that is normally enough for Google to consolidate the two.",
  "",
  "It is not fixed properly, though, and cannot be from inside this repo: a static export",
  "emits no redirects, and Cloudflare's `_redirects` file matches paths only, not hostnames.",
  "Closing it needs either a Redirect Rule in the Cloudflare dashboard or dropping the `www`",
  "route from `wrangler.jsonc`.",
  "",
);

mkdirSync("docs/seo", { recursive: true });
writeFileSync("docs/seo/keyword-map.md", out.join("\n"), "utf8");
console.log(
  `wrote docs/seo/keyword-map.md: ${pages.length} pages, ${missions.length} missions`,
);
